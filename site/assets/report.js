/* Tech Radar: daily security report. Reads reports/index.json and reports/<day>.json (facts built by the pipeline).
   All sentences are composed here from those facts with fixed rules, in Arabic or English. Nothing is generated by a model,
   and news is presented as published by its source, not as an incident the radar verified. */
(function () {
  "use strict";
  var R = window.Radar, $ = R.$, el = R.el, nf = R.nf, L = R.L;
  var idx = [], cur = null;
  var dayF = new Intl.DateTimeFormat(R.en ? "en-US" : "ar-SA-u-nu-latn-ca-gregory", { weekday: "long", day: "numeric", month: "long", year: "numeric" });
  function dayName(d) { return dayF.format(Date.parse(d + "T12:00:00+03:00")); }
  function str(v, max) { return typeof v === "string" ? v.slice(0, max || 600) : ""; }
  function num(v) { return typeof v === "number" && isFinite(v) && v >= 0 ? v : 0; }
  function cnt(n, ar, en) { return R.countL(n, ar, en); }
  var VULN = [["ثغرة", "ثغرتين", "ثغرات", "ثغرة"], ["vulnerability", "vulnerabilities"]];

  function sec(doc, title, note) {
    var s = el("section", "r-sec"); s.appendChild(el("h3", null, title));
    if (note) s.appendChild(el("p", "r-note", note));
    doc.appendChild(s); return s;
  }
  function linkTo(text, url, dir) {
    var u = R.safeUrl(url), a = el(u ? "a" : "span", null, text);
    if (u) R.link(a, u); if (dir) a.setAttribute("dir", dir); return a;
  }
  function cveCell(v) {
    var c = el("td", "r-id"), cv = R.splitCve({ title: str(v.title, 300), source: "NVD" });
    var a = el("a", null, null); a.appendChild(el("bdi", null, str(v.id, 40))); a.href = "./#v=" + encodeURIComponent(str(v.id, 40)); c.appendChild(a);
    var t = el("span", null, R.en || !v.summary ? (cv.rest || "") : str(v.summary, 400)); t.setAttribute("dir", "auto"); c.appendChild(t);
    return c;
  }

  // ---------- executive summary: fixed sentences from the counts
  function summary(r) {
    var c = r.counts || {}, out = [];
    var top = (r.top_vulns || [])[0];
    out.push(R.en
      ? "On " + dayName(r.day) + " the radar recorded " + cnt(num(c.vulns), null, VULN[1]) + " newly published in NVD, " + nf.format(num(c.critical)) + " of them critical by CVSS and " + nf.format(num(c.risk_high)) + " with a high or critical risk score."
      : "في يوم " + dayName(r.day) + " رصد الرادار " + cnt(num(c.vulns), VULN[0]) + " نُشرت في NVD، منها " + nf.format(num(c.critical)) + " حرجة حسب CVSS، و" + nf.format(num(c.risk_high)) + " درجة خطرها عالية أو حرجة.");
    if (num(c.kev_added)) out.push(R.en ? "CISA added " + cnt(num(c.kev_added), null, VULN[1]) + " to its list of exploited vulnerabilities; these come first." : "وأضافت CISA " + cnt(num(c.kev_added), VULN[0]) + " إلى قائمة الثغرات المستغلة فعلياً، وهذه أولوية التحديث الأولى.");
    else out.push(L("ولم تُضف CISA أي ثغرة إلى قائمة الثغرات المستغلة في هذا اليوم.", "CISA added no vulnerability to its exploited list that day."));
    if (top && top.risk != null) out.push(R.en ? "Highest risk: " + str(top.id, 40) + " (" + top.risk + "/100) in " + R.sysName(str(top.system, 120)) + "."
      : "أعلى ثغرة خطراً: " + str(top.id, 40) + " (" + top.risk + " من 100) في " + R.sysName(str(top.system, 120)) + ".");
    if (num(c.updates)) out.push(R.en ? "Vendors published " + nf.format(num(c.updates)) + " security updates and advisories" + (num(c.updates_action) ? ", " + nf.format(num(c.updates_action)) + " of which fix an exploited vulnerability." : ".")
      : "وأصدرت الشركات " + nf.format(num(c.updates)) + " تحديثاً ونشرة أمنية" + (num(c.updates_action) ? "، منها " + nf.format(num(c.updates_action)) + " تصلح ثغرة مستغلة." : "."));
    if (num(c.news)) out.push(R.en ? "The radar collected " + nf.format(num(c.news)) + " tech news items, " + nf.format(num(c.news_sec)) + " about security." : "وجمع الرادار " + nf.format(num(c.news)) + " خبراً تقنياً، منها " + nf.format(num(c.news_sec)) + " أمنية.");
    var col = r.collection || {}, f0 = Date.parse(col.first_cycle), l0 = Date.parse(col.last_cycle);
    if (f0 && l0) {   // disclose partial days: the radar runs on a student PC that is sometimes off
      var hf = new Date(f0 + 3 * 36e5).getUTCHours(), hl = new Date(l0 + 3 * 36e5).getUTCHours();
      if (hf >= 2 || hl < 22) out.push(R.en ? "The radar ran that day only from " + R.timeF.format(f0) + " to " + R.timeF.format(l0) + "; what appeared outside those hours was picked up by later cycles where the source still listed it."
        : "كان الرادار يعمل في هذا اليوم من " + R.timeF.format(f0) + " إلى " + R.timeF.format(l0) + " فقط، وما نُشر خارج هذه الساعات جُمع في الدورات اللاحقة إن بقي في المصدر.");
    }
    var fails = failures(r);
    if (fails.length) out.push(R.en ? "Some data collection failed that day (see the last section); the numbers may be incomplete." : "وتعذّر جلب بعض البيانات في هذا اليوم (التفاصيل في آخر التقرير)، فقد تكون الأرقام ناقصة.");
    return out;
  }
  function failures(r) {
    var s = (r.collection && r.collection.sources) || {}, f = [];
    Object.keys(s).forEach(function (k) { if (num(s[k].fail)) f.push(k); });
    return f;
  }
  // ---------- recommendations: rules tied to the records in this report
  function recommendations(r) {
    var out = [];
    (r.kev || []).slice(0, 3).forEach(function (k) {
      out.push([R.en ? "Apply CISA's required action for " + str(k.id, 40) + " (" + R.sysName(str(k.system, 120)) + ")" + (k.due ? " before " + R.fmtDate(k.due) : "") + "."
        : "طبّق الإجراء الذي تطلبه CISA للثغرة " + str(k.id, 40) + " في " + R.sysName(str(k.system, 120)) + (k.due ? " قبل " + R.fmtDate(k.due) : "") + ".",
        L("لأنها مدرجة في قائمة الثغرات المستغلة.", "Because it is in the exploited list.")]);
    });
    (r.updates || []).filter(function (u) { return u.action; }).slice(0, 3).forEach(function (u) {
      out.push([R.en ? "Install the " + str(u.vendor, 60) + " update “" + str(u.title, 140) + "”" + (u.fixed ? " (fixed version " + str(u.fixed, 80) + ")" : "") + "."
        : "ثبّت تحديث " + str(u.vendor, 60) + " «" + str(u.title, 140) + "»" + (u.fixed ? " (الإصدار المصحح " + str(u.fixed, 80) + ")" : "") + ".",
        u.kev ? L("لأنه يصلح ثغرة في قائمة CISA.", "Because it fixes a vulnerability in CISA's list.") : L("لأن الشركة تذكر أن ثغرة فيه مستغلة.", "Because the vendor says a vulnerability in it is exploited.")]);
    });
    var ex = (r.top_vulns || []).filter(function (v) { return !v.kev && v.exploit; }).slice(0, 3);
    var prods = ex.map(function (v) { return R.sysName(str(v.system, 80)); }).filter(function (x, i, a) { return a.indexOf(x) === i; });
    if (ex.length) out.push([R.en ? "Check whether you run " + prods.join(", ") + ": exploit details are public for " + ex.map(function (v) { return str(v.id, 40); }).join(", ") + "."
      : "تحقق إن كنت تستخدم " + prods.join(" أو ") + ": تفاصيل استغلال " + ex.map(function (v) { return str(v.id, 40); }).join(" و") + " منشورة.",
      L("معلومات الاستغلال المنشورة ترفع احتمال الهجوم، وإن لم يثبت استغلالها بعد.", "Public exploit details raise the chance of attack, even before exploitation is confirmed.")]);
    var crit = num((r.counts || {}).critical);
    if (crit) out.push([R.en ? "Review the " + cnt(crit, null, ["critical vulnerability", "critical vulnerabilities"]) + " of the day against the products you use, and plan their updates in your regular patch cycle."
      : "راجع الثغرات الحرجة في هذا اليوم (" + nf.format(crit) + ") مقابل المنتجات التي تستخدمها، وأدخل تحديثاتها في دورة التحديث المعتادة.",
      L("خطورتها عالية حسب CVSS، لكن لم يثبت استغلال أغلبها.", "They are severe by CVSS, but most are not known to be exploited.")]);
    if (!out.length) out.push([L("لا إجراء عاجلاً من بيانات هذا اليوم. استمر في التحديثات المعتادة.", "No urgent action from this day's data. Keep up with regular updates."), ""]);
    return out;
  }

  function render(r) {
    var doc = $("doc"); doc.textContent = ""; doc.hidden = false; cur = r;
    var head = el("header", "r-head");
    var h = el("h2", null, L("التقرير الأمني ليوم ", "Security report for ") + dayName(r.day)); h.id = "r-title"; head.appendChild(h);
    var meta = el("p", "r-meta");
    var g = Date.parse(r.generated_at);
    meta.textContent = L("الفترة: من منتصف ليل ", "Period: from midnight ") + R.fmtDate(r.day) + L(" إلى منتصف الليل التالي بتوقيت الرياض. أُنشئ التقرير ", " to the next midnight, Riyadh time. Generated ")
      + (g ? R.dateF.format(g) + L("، الساعة ", ", ") + R.timeF.format(g) : "") + ".";
    head.appendChild(meta); doc.appendChild(head);

    var s1 = sec(doc, L("الملخص التنفيذي", "Executive summary"));
    var p = el("p", "r-lead"); p.textContent = summary(r).join(" "); s1.appendChild(p);

    var c = r.counts || {}, strip = el("dl", "r-nums");
    [[L("ثغرات جديدة", "New vulnerabilities"), c.vulns], [L("حرجة (CVSS)", "Critical (CVSS)"), c.critical], [L("خطر عالٍ أو حرج", "High or critical risk"), c.risk_high],
     [L("أُضيفت لقائمة CISA", "Added to CISA's list"), c.kev_added], [L("تحديثات ونشرات", "Updates"), c.updates], [L("أخبار تقنية", "Tech news"), c.news]]
      .forEach(function (x) { var d = el("div"); d.appendChild(el("dt", null, x[0])); d.appendChild(el("dd", "num", nf.format(num(x[1])))); strip.appendChild(d); });
    s1.appendChild(strip);

    var s2 = sec(doc, L("أخطر 5 ثغرات", "Top 5 vulnerabilities"), L("مرتبة حسب درجة الخطر (من 100). الخطورة من CVSS، والاستغلال من قائمة CISA، وهما أمران منفصلان.", "Ranked by risk score (out of 100). Severity is CVSS; exploitation is CISA's list; the two are separate."));
    if (!(r.top_vulns || []).length) s2.appendChild(el("p", "r-empty", L("لم تُنشر ثغرات في هذا اليوم ضمن ما رصده الرادار.", "No vulnerabilities were published that day in what the radar tracked.")));
    else {
      var tw = el("div", "r-tw"), t = el("table", "r-table"), tr = el("tr");
      [L("الثغرة", "Vulnerability"), L("المنتج", "Product"), "CVSS", L("درجة الخطر", "Risk"), L("الاستغلال", "Exploitation"), L("المصدر", "Source")].forEach(function (x) { var th = el("th", null, x); th.scope = "col"; tr.appendChild(th); });
      var th0 = el("thead"); th0.appendChild(tr); t.appendChild(th0);
      var tb = el("tbody");
      r.top_vulns.forEach(function (v) {
        var row = el("tr"); row.appendChild(cveCell(v));
        row.appendChild(el("td", null, R.sysName(str(v.system, 120))));
        row.appendChild(el("td", "num", typeof v.score === "number" ? v.score.toFixed(1) : "—"));
        var rc = el("td"); rc.appendChild(R.riskBadge({ risk: typeof v.risk === "number" ? v.risk : null, riskLevel: R.RISK[v.risk_level] ? v.risk_level : "unknown", kev: !!v.kev })); row.appendChild(rc);
        row.appendChild(el("td", null, v.kev ? L("ثبت استغلالها (CISA)", "Known exploited (CISA)") : v.exploit ? L("استغلال منشور، غير مؤكد", "Public exploit, not confirmed") : L("لا دليل منشور", "No published evidence")));
        var sc = el("td"); sc.appendChild(linkTo("NVD", v.link)); row.appendChild(sc);
        tb.appendChild(row);
      });
      t.appendChild(tb); tw.appendChild(t); s2.appendChild(tw);
    }

    var s3 = sec(doc, L("ثغرات أُضيفت إلى قائمة الاستغلال (CISA KEV)", "Added to CISA's Known Exploited Vulnerabilities"));
    if (!(r.kev || []).length) s3.appendChild(el("p", "r-empty", L("لا توجد إضافات في هذا اليوم.", "No additions that day.")));
    else {
      var ul = el("ul", "r-list");
      r.kev.forEach(function (k) {
        var li = el("li"), a = el("a", null, null); a.appendChild(el("bdi", null, str(k.id, 40))); a.href = "./#v=" + encodeURIComponent(str(k.id, 40)); li.appendChild(a);
        li.appendChild(document.createTextNode(" " + R.sysName(str(k.system, 120)) + (typeof k.score === "number" ? " · CVSS " + k.score.toFixed(1) : "")
          + (k.due ? L("، الموعد النهائي للإصلاح ", ", remediation due ") + R.fmtDate(k.due) : "") + (k.ransom === "Known" ? L("، استُخدمت في حملات فدية", ", used in ransomware campaigns") : "")));
        ul.appendChild(li);
      });
      s3.appendChild(ul);
    }

    var s4 = sec(doc, L("أهم التحديثات الأمنية", "Important security updates"), L("من النشرات الرسمية للشركات. ما يحتاج تصرفاً أولاً.", "From the vendors' official bulletins. Those needing action first."));
    if (!(r.updates || []).length) s4.appendChild(el("p", "r-empty", L("لم تصدر تحديثات من المصادر المتابعة في هذا اليوم.", "No updates from the tracked sources that day.")));
    else {
      var ul2 = el("ul", "r-list");
      r.updates.forEach(function (u) {
        var li = el("li"); if (u.action) li.className = "act";
        li.appendChild(el("b", null, str(u.vendor, 60) + ": ")); li.appendChild(linkTo(str(u.title, 200), u.link, "auto"));
        li.appendChild(document.createTextNode(" (" + (R.UTYPE[u.utype] || "") + (u.fixed ? L("، الإصدار المصحح ", ", fixed in ") + str(u.fixed, 80) : "") + (num(u.cves) ? R.comma + cnt(num(u.cves), VULN[0], VULN[1]) : "") + ")"));
        if (u.action) li.appendChild(el("span", "r-flag", u.kev ? L("يصلح ثغرة في قائمة CISA", "Fixes a CISA-listed vulnerability") : L("الشركة تذكر استغلالاً", "Vendor reports exploitation")));
        ul2.appendChild(li);
      });
      s4.appendChild(ul2);
    }

    var s5 = sec(doc, L("الأخبار", "News"), L("عناوين منقولة عن مصادرها كما نُشرت، وليست حوادث تحقق منها الرادار. الملخصات العربية آلية وقد تخطئ.", "Headlines as published by their sources, not incidents the radar verified. Arabic summaries are machine-written and can be wrong."));
    [[L("أخبار أمنية", "Security news"), r.news_security], [L("أخبار تقنية", "Tech news"), r.news_tech]].forEach(function (grp) {
      s5.appendChild(el("h4", null, grp[0]));
      if (!(grp[1] || []).length) { s5.appendChild(el("p", "r-empty", L("لا شيء في هذا اليوم.", "Nothing that day."))); return; }
      var ul3 = el("ul", "r-list");
      grp[1].forEach(function (n) {
        var li = el("li"); li.appendChild(linkTo(str(n.title, 200), n.link, "auto"));
        li.appendChild(el("small", null, " " + R.srcName(str(n.source, 80))));
        if (!R.en && n.summary) li.appendChild(el("p", null, str(n.summary, 500)));
        ul3.appendChild(li);
      });
      s5.appendChild(ul3);
    });

    var s6 = sec(doc, L("التوصيات", "Recommendations"), L("قواعد ثابتة مبنية على سجلات هذا التقرير، وليست نصيحة مخصصة لبيئتك.", "Fixed rules based on this report's records; not advice tailored to your environment."));
    var ol = el("ol", "r-recs");
    recommendations(r).forEach(function (x) { var li = el("li"); li.appendChild(el("span", null, x[0])); if (x[1]) li.appendChild(el("small", null, x[1])); ol.appendChild(li); });
    s6.appendChild(ol);

    var col = r.collection || {}, s7 = sec(doc, L("ملخص جمع البيانات", "Data collection summary"));
    var dl = el("dl", "r-facts");
    function fact(k, v) { var d = el("div"); d.appendChild(el("dt", null, k)); d.appendChild(el("dd", null, v)); dl.appendChild(d); }
    fact(L("دورات التحديث في هذا اليوم", "Update cycles that day"), nf.format(num(col.cycles)) + (col.first_cycle ? L(" (أولها ", " (first ") + R.timeF.format(Date.parse(col.first_cycle)) + L("، وآخرها ", ", last ") + R.timeF.format(Date.parse(col.last_cycle)) + ")" : ""));
    var cc = col.collected || {};
    fact(L("سجلات جديدة جُمعت", "New records collected"), nf.format(num(cc.vuln)) + L(" ثغرة، و", " vulnerabilities, ") + nf.format(num(cc.news)) + L(" خبراً، و", " news, ") + nf.format(num(cc.update)) + L(" تحديثاً", " updates"));
    fact(L("تغيّرت درجتها في NVD", "Score changed in NVD"), nf.format(num(c.score_changes)));
    var NAMES = { kev: "CISA KEV", nvd: "NVD", rss: L("خلاصات الأخبار", "News feeds"), upd: L("نشرات الشركات", "Vendor bulletins") };
    var srcs = (col.sources) || {};
    Object.keys(NAMES).forEach(function (k) {
      var s = srcs[k];
      fact(NAMES[k], !s ? L("لم يُسجَّل في هذا اليوم", "Not recorded that day")
        : nf.format(num(s.ok)) + L(" ناجحة", " succeeded") + (num(s.fail) ? L("، و", ", ") + nf.format(num(s.fail)) + L(" فشلت: ", " failed: ") + (s.errors || []).map(function (e) { return str(e, 120); }).join(" | ") : ""));
    });
    s7.appendChild(dl);
    if (failures(r).length) { var w = el("p", "r-warn"); w.textContent = L("فشل بعض الجلب في هذا اليوم، لذا قد لا تشمل الأرقام كل ما نُشر.", "Some fetches failed that day, so the numbers may not cover everything published."); s7.appendChild(w); }
    document.querySelectorAll("#archive a").forEach(function (a) { a.setAttribute("aria-current", String(a.dataset.day === r.day)); });
  }

  function load(day) {
    $("state").textContent = "";
    fetch("reports/" + encodeURIComponent(day) + ".json", { cache: "no-cache" }).then(function (r) { if (!r.ok) throw new Error("HTTP " + r.status); return r.json(); })
      .then(function (r) { if (!r || r.day !== day) throw new Error("bad-format"); render(r); var p = new URLSearchParams(); p.set("day", day); R.setHash(p); $("day").value = day; })
      .catch(function (e) { $("doc").hidden = true; R.errorNotice($("state"), e, function () { load(day); }); });
  }
  R.status("loading");
  fetch("reports/index.json", { cache: "no-cache" }).then(function (r) { if (!r.ok) throw new Error("HTTP " + r.status); return r.json(); }).then(function (d) {
    idx = (d && Array.isArray(d.reports) ? d.reports : []).filter(function (x) { return x && /^\d{4}-\d{2}-\d{2}$/.test(x.day); });
    R.status("ok", idx.length ? Date.parse(idx[0].generated_at) || Date.now() : Date.now());
    var sel = $("day"), ar = $("archive"); sel.textContent = ""; ar.textContent = "";
    if (!idx.length) {
      $("state").appendChild(el("div", "empty", L("لا توجد تقارير بعد. أول تقرير يُبنى بعد منتصف الليل لليوم الذي سبقه.", "No reports yet. The first one is built after midnight for the day before.")));
      return;
    }
    idx.forEach(function (x) {
      var o = el("option", null, dayName(x.day)); o.value = x.day; sel.appendChild(o);
      var li = el("li"), a = el("a", null, dayName(x.day)); a.href = "#day=" + x.day; a.dataset.day = x.day;
      a.onclick = function (e) { e.preventDefault(); load(x.day); window.scrollTo({ top: 0, behavior: R.reduced ? "auto" : "smooth" }); };
      li.appendChild(a); var c = x.counts || {};
      li.appendChild(el("span", null, cnt(num(c.vulns), VULN[0], VULN[1]) + R.comma + L("حرجة ", "critical ") + nf.format(num(c.critical)) + R.comma + L("مستغلة جديدة ", "new exploited ") + nf.format(num(c.kev_added))));
      ar.appendChild(li);
    });
    sel.onchange = function () { load(sel.value); };
    var want = R.hashParams().get("day");
    load(idx.some(function (x) { return x.day === want; }) ? want : idx[0].day);
  }).catch(function (e) { R.status("error"); R.errorNotice($("state"), e, function () { location.reload(); }); });

  $("export").onclick = function () {
    if (!cur) return;
    // print a copy of the report as #print-report (the site-wide print rule shows only that element)
    var old = $("print-report"); if (old) old.remove();
    var pr = $("doc").cloneNode(true); pr.id = "print-report"; pr.hidden = false; pr.className = "r-doc r-print"; pr.removeAttribute("aria-labelledby");
    var brand = el("p", "r-brand", L("رادار التقنية · nfalqhtan-hue.github.io/radar", "Tech Radar · nfalqhtan-hue.github.io/radar")); pr.insertBefore(brand, pr.firstChild);
    document.body.appendChild(pr);
    var t0 = document.title; document.title = (R.en ? "tech-radar-daily-report-" : "تقرير-رادار-التقنية-") + cur.day;
    var restore = function () { document.title = t0; window.removeEventListener("afterprint", restore); var x = $("print-report"); if (x) x.remove(); };
    window.addEventListener("afterprint", restore);
    setTimeout(function () { window.print(); restore(); }, 50);
  };
})();
